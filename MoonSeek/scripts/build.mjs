import { build } from 'esbuild'
import { mkdir, writeFile, copyFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../', import.meta.url))
await mkdir(new URL('../lib/', import.meta.url), { recursive: true })
await copyFile(new URL('../src/index.js', import.meta.url), new URL('../lib/index.js', import.meta.url))
const result = await build({ absWorkingDir: root, entryPoints: ['src/client.jsx'], write: false,
  bundle: true, format: 'cjs', platform: 'browser', target: 'es2022',
  external: ['react'], loader: { '.css': 'text' } })
await writeFile(new URL('../lib/client.js', import.meta.url),
  '// Generated by npm run build. React is supplied by DSH.\n' +
  'window.__ModuleLoader__.load({ id: "dsh-moonseek", factory(require) {\n' +
  'const module = { exports: {} }; const exports = module.exports;\n' +
  result.outputFiles[0].text + '\nreturn module.exports;\n} });\n')
