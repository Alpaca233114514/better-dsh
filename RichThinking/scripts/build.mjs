import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
const root = fileURLToPath(new URL('../', import.meta.url))
await mkdir(new URL('../lib/', import.meta.url), { recursive: true })
await build({ absWorkingDir: root, entryPoints: ['src/index.ts'], outfile: 'lib/index.js',
  bundle: true, format: 'esm', platform: 'node', target: 'node22', external: ['@deepseek-ai/schemastery'] })
const client = await build({ absWorkingDir: root, entryPoints: ['src/client.tsx'], write: false,
  bundle: true, format: 'cjs', platform: 'browser', target: 'es2022', external: ['react', 'react-dom', '@deepseek-ai/dsh-client-ui-primitives'] })
await writeFile(new URL('../lib/client.js', import.meta.url),
  '// Generated by npm run build. React is provided by DSH.\n' +
  'window.__ModuleLoader__.load({ id: "dsh-rich-thinking", factory(require) {\n' +
  'const module = { exports: {} }; const exports = module.exports;\n' +
  client.outputFiles[0].text + '\nreturn module.exports;\n} });\n')
