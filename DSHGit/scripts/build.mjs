import { build } from 'esbuild'
import { mkdir, writeFile } from 'node:fs/promises'
await mkdir('lib', { recursive: true })
await build({ entryPoints: ['src/host.ts'], outfile: 'lib/host.js', bundle: true, tsconfig: 'tsconfig.json',
  format: 'esm', platform: 'node', target: 'es2022', external: ['@deepseek-ai/*', 'zod'],
})
const client = await build({ entryPoints: ['src/client.tsx'], write: false, bundle: true,
  format: 'cjs', platform: 'browser', target: 'es2022', jsx: 'automatic',
  external: ['@deepseek-ai/*', 'react', 'react/*', 'react-dom', 'react-dom/*'], loader: { '.css': 'text' },
  define: { 'process.env.NODE_ENV': '"production"' },
})
await writeFile('lib/client.js', `// Generated by npm run build.\nwindow.__ModuleLoader__.load({ id: "dshgit", factory(require) {\nconst module = { exports: {} }; const exports = module.exports;\n${client.outputFiles[0].text}\nreturn module.exports; } });\n`)
