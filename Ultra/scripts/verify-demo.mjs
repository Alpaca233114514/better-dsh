import assert from 'node:assert/strict';
import { fileURLToPath, pathToFileURL } from 'node:url';
const playwrightModule = process.env.PLAYWRIGHT_MODULE || 'C:/Users/Logan/Documents/GitHub/Papyrus_Desktop/node_modules/playwright/index.mjs';
const { chromium } = await import(pathToFileURL(playwrightModule));
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH || 'C:/Users/Logan/AppData/Local/ms-playwright/chromium-1248/chrome-win64/chrome.exe' });
const errors = [], checks = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(new URL('../demo/index.html', import.meta.url).href);
  const slider = page.getByRole('slider'), trigger = page.getByRole('button', { name: '推理与代理模式', exact: true });
  const open = async () => { if (!(await slider.isVisible())) await trigger.click(); };
  assert.equal(await slider.getAttribute('aria-valuetext'), 'Ultra');
  assert.equal(await page.locator('#parent-effort').textContent(), 'Max');
  assert.deepEqual(await page.locator('.effort-select').evaluateAll(els => els.map(el => el.value)), ['max', 'max', 'max']);
  assert.equal(await page.locator('.rs-spark').count(), 20);
  await page.screenshot({ path: fileURLToPath(new URL('../demo/ultra-dark.png', import.meta.url)) });
  await slider.press('ArrowLeft'); await page.waitForTimeout(450);
  assert.equal(await slider.getAttribute('aria-valuetext'), 'Max');
  assert.equal(await page.locator('.rs-max-field').count(), 0);
  assert.equal(await page.locator('#parent-effort').textContent(), 'Max');
  await slider.press('End');
  assert.equal(await page.locator('.rs-max-field').getAttribute('data-reveal'), '');
  await trigger.click(); await trigger.click();
  assert.equal(await page.locator('.rs-max-field').getAttribute('data-reveal'), null);
  checks.push('Ultra -> max request, child defaults, exclusive effects, reopen without replay');
  await page.locator('#prompt').fill('保留这个草稿');
  await page.getByRole('switch').uncheck(); await open();
  assert.equal(await slider.getAttribute('aria-valuemax'), '3');
  assert.equal(await slider.getAttribute('aria-valuetext'), 'Max');
  assert.equal(await page.locator('.rs-max-field').count(), 1);
  await page.screenshot({ path: fileURLToPath(new URL('../demo/max-fallback.png', import.meta.url)) });
  await page.getByRole('switch').check(); await open(); await page.waitForTimeout(450);
  assert.equal(await slider.getAttribute('aria-valuetext'), 'Max');
  assert.equal(await page.locator('.rs-max-field').count(), 0);
  await slider.press('End');
  await page.getByLabel('接口检查思考强度').selectOption('high');
  assert.equal(await page.getByLabel('接口检查思考强度').inputValue(), 'high');
  assert.equal(await page.getByLabel('界面检查思考强度').inputValue(), 'max');
  assert.equal(await page.locator('#parent-effort').textContent(), 'Max');
  await page.getByRole('button', { name: '全部恢复 Max' }).click();
  assert.equal(await page.getByLabel('接口检查思考强度').inputValue(), 'max');
  checks.push('Plugin availability fallback, no automatic reactivation, independent child effort and reset');
  await open();
  const box = await slider.boundingBox();
  await page.mouse.move(box.x + 14, box.y + box.height / 2); await page.mouse.down();
  await page.mouse.move(box.x + 14 + (box.width - 28) * .64, box.y + box.height / 2);
  assert.equal(await slider.getAttribute('aria-valuenow'), '3');
  await page.mouse.up(); await slider.press('End');
  await slider.press('Escape'); assert.equal(await page.locator('#panel').isVisible(), false);
  await page.getByRole('button', { name: '演示运行' }).click();
  assert.equal(await page.getByRole('switch').isDisabled(), true);
  await page.waitForTimeout(800);
  assert.equal(await page.locator('[data-state=running]').count(), 3);
  await page.screenshot({ path: fileURLToPath(new URL('../demo/ultra-running.png', import.meta.url)) });
  await page.getByRole('button', { name: '停止演示' }).click();
  await page.waitForTimeout(700);
  assert.equal(await page.locator('#run-state').textContent(), '已停止');
  await page.getByRole('button', { name: '再次演示' }).click();
  await page.waitForFunction(() => document.getElementById('run-state').textContent === '演示完成');
  assert.equal(await page.locator('[data-state=done]').count(), 3);
  assert.equal(await page.locator('#prompt').inputValue(), '保留这个草稿');
  checks.push('Discrete pointer and keyboard navigation, Escape, cancellation, parallel lifecycle, completion, draft retention');
  await page.getByRole('button', { name: '切换浅色主题' }).click(); await open();
  await page.screenshot({ path: fileURLToPath(new URL('../demo/ultra-light.png', import.meta.url)) });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  assert.equal(await page.locator('.rs-spark').first().evaluate(el => getComputedStyle(el).animationName), 'none');
  await page.setViewportSize({ width: 1100, height: 800 });
  await page.locator('#trigger').scrollIntoViewIfNeeded(); await open();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  const popover = await page.locator('#panel').boundingBox();
  assert(popover.x >= 0 && popover.x + popover.width <= 1100);
  await page.screenshot({ path: fileURLToPath(new URL('../demo/ultra-desktop-compact.png', import.meta.url)) });
  checks.push('Light/dark, reduced motion, desktop window and popover placement');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ passed: checks, pageErrors: errors }, null, 2));
} finally { await browser.close(); }
