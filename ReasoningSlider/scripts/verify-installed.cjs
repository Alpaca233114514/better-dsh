const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const { pathToFileURL } = require('node:url');
const [runtime, profile, backup, receipt] = process.argv.slice(2);
const readJson = file => JSON.parse(fs.readFileSync(file, 'utf8'));
(async () => {
  const source = readJson(path.join(__dirname, '../package.json'));
  const name = source.name;
  const replacedNames = new Set([name, 'dsh-reasoning-slider']);
  const before = readJson(path.join(backup, 'package.json'));
  const after = readJson(path.join(profile, 'package.json'));
  const dir = path.join(profile, 'node_modules', name);
  const installed = readJson(path.join(dir, 'package.json'));
  const official = await import(pathToFileURL(path.join(runtime, 'node_modules/@deepseek-ai/dsh-app-boot/lib/index.js')).href);
  const runtimeVersion = official.getDshRuntimeVersion();
  assert.equal(official.evaluatePluginCompatibility(installed, {}, runtimeVersion), undefined);
  assert.equal(installed.version, source.version);
  assert.deepEqual(after.dsh.profile.bundles.filter(item => !replacedNames.has(item)), before.dsh.profile.bundles.filter(item => !replacedNames.has(item)));
  assert(!after.dsh.profile.bundles.includes('dsh-reasoning-slider'));
  assert(after.dsh.profile.bundles.includes(name));
  assert(after.dsh.profile.bundles.includes('@deepseek-ai/dsh-experimental-auto-review'));
  for (const [key, value] of Object.entries(before.dependencies)) if (!replacedNames.has(key)) assert.equal(after.dependencies[key], value);
  assert.equal(fs.readFileSync(path.join(profile, 'cordis.patch.yml'), 'utf8'), fs.readFileSync(path.join(backup, 'cordis.patch.yml'), 'utf8'));
  assert(!fs.existsSync(path.join(dir, 'debug')));
  assert(!fs.existsSync(path.join(dir, 'demo')));
  let registration;
  vm.runInNewContext(fs.readFileSync(path.join(dir, 'lib/client.js'), 'utf8'), {window:{__ModuleLoader__:{load(value){registration=value;}}}});
  assert.equal(registration.id, name);
  const host = await import(pathToFileURL(path.join(dir, 'lib/index.js')).href);
  assert.equal(typeof host.apply, 'function');
  const result = {version:installed.version,runtime:runtimeVersion,enabled:true,previousBundlesPreserved:true,autoReviewPreserved:true,previousDependenciesPreserved:true,profilePatchUnchanged:true,debugCatalogNotInstalled:true,clientRegistered:true};
  fs.writeFileSync(receipt, JSON.stringify(result,null,2)+'\n');
  console.log(JSON.stringify(result));
})().catch(error => { console.error(error.message); process.exitCode=1; });
