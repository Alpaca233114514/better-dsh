import { build } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
await mkdir('lib', { recursive: true })
// Keep the legacy dynamic halves and native package on the same implementation.
await writeFile('src/generated-host.js', 'export function createMeter(harness) {\n' + await readFile('host.js', 'utf8') + '\n}\n')
await writeFile('src/generated-client.js', 'export function createMeterClient(React, host, styles) {\n' + await readFile('client.js', 'utf8') + '\n}\n')
await build({ entryPoints: ['src/host.ts'], outfile: 'lib/host.js', bundle: true,
  format: 'esm', platform: 'node', target: 'es2022', tsconfigRaw: {}, external: ['@deepseek-ai/*', 'zod'] })
const client = await build({ entryPoints: ['src/client.ts'], write: false, bundle: true,
  format: 'cjs', platform: 'browser', target: 'es2022', tsconfigRaw: {}, external: ['react'] })
await writeFile('lib/client.js', `// Generated by npm run build. React is provided by DSH.\nwindow.__ModuleLoader__.load({ id: "dsh-token-meter-dashboard", factory(require) {\nconst module = { exports: {} }; const exports = module.exports;\n${client.outputFiles[0].text}\nreturn module.exports; } });\n`)
